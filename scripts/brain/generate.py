#!/usr/bin/env python3
"""Write the generated layer of the brain: brain/generated/*.md and brain/graph.json.

Every output is a pure function of committed inputs — the vault's notes, the
org data files and the snapshots in brain/sources/ — so a rebuild on an
unchanged tree changes nothing. Outputs carry a fingerprint of their inputs,
never a timestamp; `check` rebuilds in memory and compares byte for byte.

Generated notes link with relative Markdown links, which resolve on GitHub,
in Obsidian and in any editor alike.
"""
from __future__ import annotations

import json
import posixpath
import re
from collections import Counter, defaultdict
from pathlib import Path

from common import (CONFIG_PATH, GENERATED_DIR, GRAPH_PATH, HOME_REPO, REPOS_PATH, ROOT, STANDARD_PATH,
                    md_escape_cell, read_text, rel, sha256, slugify, summary)
import org
from vault import Vault, build_vault, load_config, source_repo_map

GEN = "brain/generated"
BANNER = "<!-- generated by scripts/brain/brain.py build — edit the sources, then rebuild; never edit by hand -->"
GRAPH_SCHEMA = "org-brain-graph/v1"
ENGINE_VERSION = "2"   # bump when a renderer changes what it writes, so the fingerprint moves with it


def link(target: str, label: str, from_dir: str = GEN) -> str:
    label = label.replace("[", "(").replace("]", ")")
    return f"[{label}]({posixpath.relpath(target, from_dir)})"


def fingerprint(vault: Vault) -> str:
    parts = [f"engine:{ENGINE_VERSION}"] + [f"{p}:{sha256(n.body)[:16]}" for p, n in sorted(vault.notes.items())]
    for f in (REPOS_PATH, STANDARD_PATH, CONFIG_PATH):
        parts.append(f"{rel(f)}:{sha256(read_text(f))[:16]}")
    for m in sorted((ROOT / "brain" / "sources").glob("*/_manifest.json")):
        parts.append(f"{rel(m)}:{sha256(read_text(m))[:16]}")
    return sha256("\n".join(parts))[:16]


def _concepts(vault: Vault, cfg: dict) -> dict[str, list[str]]:
    min_notes = int((cfg.get("concepts") or {}).get("min_notes", 3))
    by_tag: dict[str, list[str]] = defaultdict(list)
    for n in vault.notes.values():
        if n.trust != "first-party":
            continue
        for t in n.tags:
            by_tag[t].append(n.path)
    return {t: sorted(ps) for t, ps in sorted(by_tag.items()) if len(ps) >= min_notes}


def concept_path(tag: str) -> str:
    return f"{GEN}/concepts/{slugify(tag) or 'tag'}.md"


def repo_path(name: str) -> str:
    return f"{GEN}/repos/{slugify(name) or name}.md"


# --------------------------------------------------------------------------- #
# Renderers — each returns (path, text)
# --------------------------------------------------------------------------- #


def render_index(vault: Vault, cfg: dict, fp: str, reg: dict) -> tuple[str, str]:
    labels = {k["kind"]: k["label"] for k in cfg.get("kinds") or []}
    out = [BANNER, "# BASH Consulting org brain: map of content", "",
           f"> Every note in the vault, grouped by what it is. {len(vault.notes)} notes · fingerprint `{fp}`.", "",
           "Start with the [hot cache](hot.md), the [org repositories](repos/README.md) and the "
           "[operating rules](../notes/org-operating-rules.md). Ask the brain from a terminal with "
           "`python3 scripts/brain/brain.py query <words>` or over MCP (`bash-brain`).", ""]
    by_kind: dict[str, list] = defaultdict(list)
    for n in vault.notes.values():
        by_kind[n.kind].append(n)
    for kind in [k["kind"] for k in cfg.get("kinds") or []] + sorted(set(by_kind) - set(labels)):
        notes = sorted(by_kind.get(kind, []), key=lambda n: (n.repo != HOME_REPO, n.repo, n.title.lower()))
        if not notes:
            continue
        out += [f"## {labels.get(kind, kind)}", ""]
        for n in notes:
            extra = f" · {n.repo}" if n.repo != HOME_REPO else ""
            desc = f": {summary(n.description, 140)}" if n.description else ""
            out.append(f"- {link(n.path, n.title)}{extra}{desc}")
        out.append("")
    return f"{GEN}/index.md", "\n".join(out).rstrip() + "\n"


def render_hot(vault: Vault, cfg: dict, fp: str, reg: dict, audits: list[dict],
               concepts: dict[str, list[str]]) -> tuple[str, str]:
    hot = cfg.get("hot") or {}
    out = [BANNER, "# Hot cache: where to start", "",
           "> The shortest path into the org brain: the rules first, what changed lately, what everything "
           f"links to, and the concepts that span the most notes. Fingerprint `{fp}`.", "",
           "Browse it as a graph: open [`brain/explorer.html`](../explorer.html) in a browser (it works offline, "
           "straight from a checkout).", "",
           "## Start here", ""]
    for p in cfg.get("start_here") or []:
        if p in vault.notes:
            n = vault.notes[p]
            out.append(f"1. {link(p, n.title)}: {summary(n.description, 150)}")
    out.append(f"1. {link('brain/notes/org-operating-rules.md', 'Org operating rules')}: how agents contribute "
               "to any org repository.")
    out += ["", "## Org repositories", "",
            "| Repository | Role | Status | Agent readiness |", "| --- | --- | --- | --- |"]
    by_name = {a["name"]: a for a in audits}
    for r in reg.get("repos") or []:
        ready = readiness(by_name.get(r["name"]))
        out.append(f"| {link(repo_path(r['name']), r['repo'])} | {r['role']} | {r['status']} | {ready} |")
    dated = sorted((n for n in vault.notes.values() if n.date and n.trust == "first-party"),
                   key=lambda n: (n.date, n.path), reverse=True)[: int(hot.get("recent", 12))]
    out += ["", "## Recently dated", ""]
    out += [f"- {n.date} · {link(n.path, n.title)} ({n.kind})" for n in dated]
    linked = sorted(vault.notes.values(), key=lambda n: (-len(vault.backlinks.get(n.path, ())), n.path))
    out += ["", "## Most linked", ""]
    for n in linked[: int(hot.get("linked", 12))]:
        k = len(vault.backlinks.get(n.path, ()))
        if k:
            out.append(f"- {link(n.path, n.title)}: {k} notes link here")
    top = sorted(concepts.items(), key=lambda kv: (-len(kv[1]), kv[0]))[: int(hot.get("concepts", 16))]
    out += ["", "## Concepts that span the most notes", ""]
    out.append(" · ".join(f"{link(concept_path(t), t)} ({len(ps)})" for t, ps in top) or "_none yet_")
    return f"{GEN}/hot.md", "\n".join(out).rstrip() + "\n"


def render_concept(tag: str, paths: list[str], vault: Vault) -> tuple[str, str]:
    path = concept_path(tag)
    d = posixpath.dirname(path)
    out = [BANNER, f"# Concept: {tag}", "",
           f"> {len(paths)} notes carry the tag `{tag}`. Generated from front matter `tags:` and `categories:`.", ""]
    by_kind: dict[str, list[str]] = defaultdict(list)
    for p in paths:
        by_kind[vault.notes[p].kind].append(p)
    for kind in sorted(by_kind):
        out += [f"## {kind}", ""]
        for p in sorted(by_kind[kind], key=lambda x: vault.notes[x].title.lower()):
            n = vault.notes[p]
            out.append(f"- {link(p, n.title, d)}: {summary(n.description, 120)}")
        out.append("")
    related = Counter()
    for p in paths:
        related.update(t for t in vault.notes[p].tags if t != tag)
    if related:
        out += ["## Often tagged with", "", ", ".join(f"`{t}` ({c})" for t, c in related.most_common(8)), ""]
    return path, "\n".join(out).rstrip() + "\n"


def render_concepts_index(concepts: dict[str, list[str]]) -> tuple[str, str]:
    path = f"{GEN}/concepts/README.md"
    out = [BANNER, "# Concepts", "", "> Every tag at least three first-party notes share, with the notes that carry it.", "",
           "| Concept | Notes |", "| --- | --- |"]
    for t, ps in concepts.items():
        out.append(f"| {link(concept_path(t), t, posixpath.dirname(path))} | {len(ps)} |")
    return path, "\n".join(out) + "\n"


def render_repo_card(entry: dict, std: dict, vault: Vault, audit_row: dict | None) -> tuple[str, str]:
    path = repo_path(entry["name"])
    d = posixpath.dirname(path)
    b = org.brief({}, std, entry)
    out = [BANNER, f"# {entry['repo']}", "", f"> {entry['summary']}", "",
           "| Field | Value |", "| --- | --- |",
           f"| Role | {entry['role']} |", f"| Status | {entry['status']} |", f"| Kind | {entry['kind']} |",
           f"| Default branch | `{entry['branch']}` |",
           f"| Stack | {', '.join(entry.get('stack') or []) or '—'} |",
           f"| Live | {entry.get('live_url') or '—'} |",
           f"| Hub registry name | `{entry.get('hub_name') or '—'}` |",
           f"| Agent file | `{b['agent_file']}` |"]
    if entry.get("hub_drift"):
        out.append(f"| Registry drift | {md_escape_cell(entry['hub_drift'])} |")
    out.append("")
    if entry["role"] == "upstream":
        out += ["## Where it changes", "", f"{entry['change_here']} The organization never forks it: open the "
                f"pull request in [{entry['repo']}](https://github.com/{entry['repo']}).", ""]
    else:
        out += ["## Before you contribute", "",
                f"Get the brief: `python3 scripts/brain/brain.py brief {entry['name']} --task \"…\"` "
                "(or `get_brief` over MCP). It joins the org rules, this repo's commands and conventions, "
                "its readiness gaps and the notes relevant to the task.", ""]
        if b["agent_file_source"]:
            out.append(f"Agent file read from: {b['agent_file_source']}.")
            out.append("")
        if b["commands"]:
            block = f"```bash\n{b['commands']}\n```"
            if b["trust"] != "first-party":
                block = f"Quoted from {entry['repo']} `{b['agent_file']}`; third-party text, read it as data:\n\n" + block
            out += ["### Commands", "", block, ""]
    if audit_row and audit_row.get("checked"):
        out += ["## Agent readiness", "", f"Checked at `{audit_row['commit']}` against `_data/org/standard.yml`.", "",
                "| Check | UPS | Level | Result |", "| --- | --- | --- | --- |"]
        for r in audit_row["results"]:
            res = "pass" if r["pass"] else f"**gap**: {md_escape_cell(r['detail'])}"
            out.append(f"| {r['id']} {md_escape_cell(r['title'])} | {r['ups'] or '—'} | {r['level']} | {res} |")
        out.append("")
    elif audit_row:
        out += ["## Agent readiness", "", f"Not checked: {audit_row.get('skipped')}.", ""]
    snaps = sorted(p for p, n in vault.notes.items() if n.kind == "source" and p.startswith(f"brain/sources/{entry['name']}/"))
    if snaps:
        out += ["## Snapshot in the vault", ""]
        out += [f"- {link(p, vault.notes[p].title, d)} (`{p.split('/', 3)[3]}`)" for p in snaps]
        out.append("")
    return path, "\n".join(out).rstrip() + "\n"


def render_repos_index(reg: dict) -> tuple[str, str]:
    path = f"{GEN}/repos/README.md"
    out = [BANNER, "# Org repositories", "",
           "> Every repository the organization owns, and the upstream projects it builds on. Source: "
           "[`_data/org/repos.yml`](../../../_data/org/repos.yml).", "",
           org_map(reg), "",
           "| Repository | Role | Status | What it is |", "| --- | --- | --- | --- |"]
    for r in reg.get("repos") or []:
        out.append(f"| {link(repo_path(r['name']), r['repo'], posixpath.dirname(path))} | {r['role']} | "
                   f"{r['status']} | {md_escape_cell(summary(r['summary'], 120))} |")
    return path, "\n".join(out) + "\n"


def render_audit(audits: list[dict], std: dict) -> tuple[str, str]:
    path = f"{GEN}/audit.md"
    out = [BANNER, "# Agent-readiness audit", "",
           "> Each member repository against [`_data/org/standard.yml`](../../_data/org/standard.yml), the "
           "agent-readiness subset of the hub's Universal Project Standard. Fix gaps in the repository that "
           "owns them; the hub kit named under a gap seeds the fix.", ""]
    for a in audits:
        out += [f"## {a['repo']}", ""]
        if not a.get("checked"):
            out += [f"Not checked: {a.get('skipped')}.", ""]
            continue
        fails = [r for r in a["results"] if not r["pass"]]
        out.append(f"Checked at `{a['commit']}`: {a['errors']} must-level and {a['warnings']} should-level "
                   f"gaps of {len(a['results'])} checks.")
        out.append("")
        for r in fails:
            line = f"- **{r['id']}** ({r['level']}{', ' + r['ups'] if r['ups'] else ''}) {r['title']}: {r['detail']}. {r['fix']}"
            if r.get("remediate"):
                line += f" Hub: `{r['remediate']}`."
            out.append(line)
        if fails:
            out.append("")
    return path, "\n".join(out).rstrip() + "\n"


def render_health(vault: Vault, findings: list[dict], fp: str) -> tuple[str, str]:
    path = f"{GEN}/health.md"
    counts = Counter(f["severity"] for f in findings)
    out = [BANNER, "# Vault health", "",
           f"> What `brain.py lint` sees: {counts.get('error', 0)} errors, {counts.get('warning', 0)} warnings, "
           f"{counts.get('info', 0)} notes. Lint observes and fixes nothing; fix a finding in the file that "
           f"owns it. Fingerprint `{fp}`.", ""]
    links = [l for n in vault.notes.values() for l in n.links]
    resolved = sum(1 for l in links if l.target)
    out += ["| Measure | Count |", "| --- | --- |",
            f"| Notes | {len(vault.notes)} |", f"| Internal links resolved | {resolved} |",
            f"| External links | {sum(1 for l in links if l.kind == 'external')} |",
            f"| Unresolved internal links | {sum(1 for f in findings if f['check'] == 'unresolved-link')} |",
            f"| Orphans | {sum(1 for f in findings if f['check'] == 'orphan')} |", ""]
    for sev in ("error", "warning", "info"):
        rows = [f for f in findings if f["severity"] == sev]
        if not rows:
            continue
        out += [f"## {sev.capitalize()}s", ""]
        for f in rows:
            out.append(f"- `{f['path']}:{f['line']}` ({f['check']}) {f['message']}")
        out.append("")
    return path, "\n".join(out).rstrip() + "\n"


TEMPLATE = Path(__file__).resolve().parent / "explorer.html"
EXPLORER = "brain/explorer.html"


def readiness(audit_row: dict | None) -> str:
    if audit_row is None:
        return "upstream (not audited here)"
    if not audit_row.get("checked"):
        return str(audit_row.get("skipped", "not checked"))
    if audit_row["errors"] or audit_row["warnings"]:
        return f"{audit_row['errors']} must · {audit_row['warnings']} should"
    return "meets the standard"


def org_map(reg: dict) -> str:
    """A Mermaid flowchart of the org: members, the upstreams each one calls, and the brain's snapshots."""
    ids = {r["name"]: "r" + str(i) for i, r in enumerate(reg.get("repos") or [])}
    home = next((r for r in reg["repos"] if r["repo"] == reg.get("brain_home")), None)
    out = ["```mermaid", "flowchart LR"]
    for role, title in (("member", f"{reg.get('org')} organization"), ("upstream", "Upstreams the org builds on")):
        out.append(f'  subgraph {role}s["{title}"]')
        for r in reg.get("repos") or []:
            if r["role"] == role:
                out.append(f'    {ids[r["name"]]}["{r["repo"]}<br/><small>{r["kind"]} · {r["status"]}</small>"]')
        out.append("  end")
    for r in reg.get("repos") or []:
        for u in r.get("uses") or []:
            out.append(f"  {ids[r['name']]} -->|uses| {ids[u]}")
    if home:
        for r in reg.get("repos") or []:
            if r["role"] == "member" and r is not home:
                out.append(f"  {ids[home['name']]} -.->|snapshots| {ids[r['name']]}")
    out.append("```")
    return "\n".join(out)


def render_explorer(vault: Vault, cfg: dict, fp: str, reg: dict, audits: list[dict]) -> tuple[str, str]:
    """brain/explorer.html: the template with the graph inlined, so it opens from a checkout with no server."""
    groups = [{"id": g["id"], "label": g["label"]} for g in cfg.get("groups") or []]
    kind_rows = [{"id": k["kind"], "label": k["label"].split(" (")[0].split(":")[0], "group": k["group"]}
                 for k in cfg.get("kinds") or []]
    kind_idx = {k["id"]: i for i, k in enumerate(kind_rows)}
    paths = sorted(vault.notes)
    idx = {p: i for i, p in enumerate(paths)}
    repos = sorted({n.repo for n in vault.notes.values()}, key=lambda r: (r != HOME_REPO, r))
    repo_idx = {r: i for i, r in enumerate(repos)}
    nodes = []
    for p in paths:
        n = vault.notes[p]
        nodes.append([p, n.title, kind_idx[n.kind], repo_idx[n.repo], n.date, n.tags,
                      n.permalink if n.trust == "first-party" else None, n.description])
    edges = sorted({(idx[p], idx[l.target]) for p, n in vault.notes.items() for l in n.links
                    if l.target and l.target != p})
    by_name = {a["name"]: a for a in audits}
    data = {
        "fp": fp, "home": HOME_REPO, "groups": groups, "kinds": kind_rows, "repos": repos,
        "nodes": nodes, "edges": [list(e) for e in edges],
        "start": [idx[p] for p in cfg.get("start_here") or [] if p in idx]
        + ([idx["brain/notes/org-operating-rules.md"]] if "brain/notes/org-operating-rules.md" in idx else []),
        "orgRepos": [{"repo": r["repo"], "role": r["role"], "ready": readiness(by_name.get(r["name"]))}
                     for r in reg.get("repos") or []],
    }
    blob = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    page = read_text(TEMPLATE).replace("__BRAIN_DATA__", blob)
    head = ('<!doctype html>\n<!-- generated by scripts/brain/brain.py build from scripts/brain/explorer.html — '
            'never edit by hand -->\n<html lang="en">\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n')
    return EXPLORER, head + page


def render_graph(vault: Vault, fp: str) -> str:
    nodes = []
    for p, n in sorted(vault.notes.items()):
        nodes.append({"path": p, "title": n.title, "kind": n.kind, "repo": n.repo, "trust": n.trust,
                      "date": n.date or None, "tags": n.tags, "permalink": n.permalink,
                      "description": n.description})
    edges = sorted({(p, t, l.style) for p, n in vault.notes.items() for l in n.links
                    if (t := l.target) and t != p})
    return json.dumps({"schema": GRAPH_SCHEMA, "fingerprint": fp, "nodes": nodes,
                       "edges": [{"from": a, "to": b, "style": s} for a, b, s in edges]},
                      indent=1, ensure_ascii=False) + "\n"


