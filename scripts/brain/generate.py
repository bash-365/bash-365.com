def outputs() -> tuple[dict[str, str], dict]:
    """Every generated file as {repo-relative path: text}, plus a status summary."""
    cfg = load_config()
    reg = org.load_registry()
    std = org.load_standard()
    vault = build_vault(cfg=cfg, repo_of=source_repo_map(reg))
    fp = fingerprint(vault)
    audits = org.audit(reg, std)
    findings = vault.lint()
    concepts = _concepts(vault, cfg)
    files: dict[str, str] = {}
    for path, text in (
        render_index(vault, cfg, fp, reg),
        render_hot(vault, cfg, fp, reg, audits, concepts),
        render_repos_index(reg),
        render_audit(audits, std),
        render_health(vault, findings, fp),
        render_concepts_index(concepts),
    ):
        files[path] = text
    by_name = {a["name"]: a for a in audits}
    for entry in reg.get("repos") or []:
        path, text = render_repo_card(entry, std, vault, by_name.get(entry["name"]))
        files[path] = text
    for tag, paths in concepts.items():
        path, text = render_concept(tag, paths, vault)
        files[path] = text
    files[rel(GRAPH_PATH)] = render_graph(vault, fp)
    path, text = render_explorer(vault, cfg, fp, reg, audits)
    files[path] = text
    files[f"{GEN}/audit.json"] = json.dumps(audits, indent=2, sort_keys=True) + "\n"
    status = {"fingerprint": fp, "notes": len(vault.notes), "concepts": len(concepts),
              "findings": dict(Counter(f["severity"] for f in findings)),
              "registry_errors": org.validate_registry(reg), "standard_errors": org.validate_standard(std)}
    return files, status


def write(files: dict[str, str]) -> list[str]:
    """Write outputs; drop generated files no longer produced. Returns the changed paths."""
    changed = []
    keep = set(files)
    for old in sorted(GENERATED_DIR.rglob("*")) if GENERATED_DIR.exists() else []:
        if old.is_file() and rel(old) not in keep:
            old.unlink()
            changed.append(rel(old))
    for path, text in sorted(files.items()):
        target = ROOT / path
        if target.exists() and read_text(target) == text:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        changed.append(path)
    return changed


def stale(files: dict[str, str]) -> list[str]:
    """Paths whose committed content differs from a fresh build (or that should not exist)."""
    out = [p for p, t in sorted(files.items()) if read_text(ROOT / p) != t]
    if GENERATED_DIR.exists():
        out += [rel(f) for f in sorted(GENERATED_DIR.rglob("*")) if f.is_file() and rel(f) not in files]
    return out


